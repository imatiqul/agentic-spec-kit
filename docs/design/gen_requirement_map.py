"""Generate requirement-map.md from requirement-map.src.txt and fail if any requirement ID in the spec is unmapped."""
import re,sys,glob,os
here=os.path.dirname(os.path.abspath(__file__)); spec=os.path.join(here,'..','prompts','spec')
ids={}
for f in sorted(glob.glob(os.path.join(spec,'*.md'))):
    for m in re.finditer(r'^- ((?:GOV|TRC|MAP|CHG|QLT|AGT|ADP)-\d+) \[([^\]]+)\] (.*)$',open(f).read(),re.M):
        ids[m.group(1)]=(m.group(2),m.group(3))
rows={}
for l in open(os.path.join(here,'requirement-map.src.txt')):
    if l.startswith('#') or not l.strip(): continue
    p=[x.strip() for x in l.split('|')]
    assert len(p)==5, l
    rows[p[0]]=p[1:]
missing=sorted(set(ids)-set(rows)); extra=sorted(set(rows)-set(ids))
if missing or extra: sys.exit(f'unmapped: {missing}; unknown: {extra}')
key=lambda i:(['GOV','TRC','QLT','MAP','CHG','AGT','ADP'].index(i.split('-')[0]),int(i.split('-')[1]))
name={'E':'Enforced','S':'Enforced with repository settings','P':'Procedural','D':'Designed in Phase 9'}
out=['# Requirement to component map','','Generated by `gen_requirement_map.py` from `requirement-map.src.txt`. Do not edit by hand.','',
'Enforcement levels: **Enforced** by a deterministic check; **Enforced with repository settings** means the check passes only when an administrator has configured the enforcement channel; **Procedural** means the kit structures the work but compliance depends on a human or agent; **Designed in Phase 9** means slice 0.4, where only the component is named now.','']
from collections import Counter
c=Counter((ids[i][0],rows[i][2]) for i in ids)
out+=['| Slice | Enforced | With settings | Procedural | Designed later | Total |','|---|---|---|---|---|---|']
for s in ['0.1','0.2','0.3','0.4','later']:
    t=[c[(s,k)] for k in 'ESPD']; out.append(f'| {s} | {t[0]} | {t[1]} | {t[2]} | {t[3]} | {sum(t)} |')
out+=['','| ID | Slice | Component | Checks | Enforcement | Note |','|---|---|---|---|---|---|']
for i in sorted(ids,key=key):
    comp,chk,lvl,note=rows[i]; out.append(f'| {i} | {ids[i][0]} | {comp} | {chk} | {name[lvl]} | {note} |')
open(os.path.join(here,'requirement-map.md'),'w').write('\n'.join(out)+'\n')
print(len(ids),'requirements mapped;',dict(Counter(rows[i][2] for i in ids)))
