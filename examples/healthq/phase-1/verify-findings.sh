#!/usr/bin/env bash
# Reproduces every count in phase-1-verification.md. Usage: verify-findings.sh <path-to-healthcare-repo>
# Read-only: uses git and grep only.
set -u
cd "$1" || exit 2
E='\.Map(Get|Post|Put|Patch|Delete)\('
c(){ printf '%-58s %s\n' "$1" "$2"; }
echo "commit: $(git rev-parse HEAD) ($(git log -1 --format=%cd --date=short))"
echo "--- C1"
c "services calling AddHealthcareAuth" "$(grep -rln 'AddHealthcareAuth(builder' --include=Program.cs src | wc -l)"
c "demo handler fallback (file:line)" "$(grep -n 'DemoAnonymousAuthHandler.SchemeName)' src/HealthQCopilot.Infrastructure/Auth/JwtBearerExtensions.cs | head -1 | cut -d: -f1)"
echo "--- C2"
c "minimal API endpoints" "$(grep -rnE "$E" --include=*.cs src | wc -l)"
c "controller actions" "$(grep -rnE '^\s*\[Http(Get|Post|Put|Patch|Delete)' --include=*.cs src | wc -l)"
c "RequireAuthorization calls (excluding comments)" "$(grep -rn 'RequireAuthorization' --include=*.cs src | grep -v '///' | wc -l)"
c "[Authorize] attributes" "$(grep -rnE '^\s*\[Authorize' --include=*.cs src | wc -l)"
c "endpoints in the 3 authorized groups" "$(cat src/HealthQCopilot.Identity/Endpoints/AuditExportEndpoints.cs src/HealthQCopilot.Identity/Endpoints/TenantOnboardingEndpoints.cs src/HealthQCopilot.Ocr/Endpoints/OcrEndpoints.cs | grep -cE "$E")"
echo "--- C3"
c "X-Tenant-Id header reads" "$(grep -rn 'Headers\["X-Tenant-Id"\]' --include=*.cs src | wc -l)"
c "X-User-Id header reads" "$(grep -rn 'Headers\["X-User-Id"\]' --include=*.cs src | wc -l)"
c "break-glass group RequireAuthorization" "$(grep -c 'RequireAuthorization' src/HealthQCopilot.Identity/Endpoints/BreakGlassEndpoints.cs)"
echo "--- C4"
for f in $(grep -rl 'UseMiddleware<PhiAuditMiddleware>' --include=Program.cs src | sort); do
  a=$(grep -n 'UseMiddleware<PhiAuditMiddleware>' "$f" | cut -d: -f1); b=$(grep -n 'app.UseAuthentication' "$f" | cut -d: -f1)
  c "$f" "audit line $a, authentication line $b"; done
c "services with their own audit table registration" "$(grep -rn 'AddHealthcareDb<AuditDbContext>' --include=Program.cs src | wc -l)"
c "migrations mentioning phi_audit_logs" "$(grep -rl 'phi_audit_logs\|PhiAuditLogs' --include=*.cs src | grep -c Migrations)"
c "RLS statements outside comments" "$(grep -rnE 'ENABLE ROW LEVEL SECURITY|CREATE POLICY' --include=*.cs --include=*.sql src infra | grep -vc '//')"
echo "--- C5"
c "classifier input is transcript + RAG (line)" "$(grep -n 'transcriptText + Environment.NewLine + Environment.NewLine + ragContext' src/HealthQCopilot.Agents/Services/TriageOrchestrator.cs | cut -d: -f1)"
c "keyword rules in TriagePlugin" "$(grep -c 'ContainsAny(lower' src/HealthQCopilot.Agents/Plugins/TriagePlugin.cs)"
echo "--- C6"
c "classifier references in eval code" "$(grep -rn 'TriagePlugin\|ClassifyUrgency\|TriageOrchestrator\|classify_urgency' tests/HealthQCopilot.Tests.Eval src/HealthQCopilot.Agents/Evaluation | wc -l)"
c "golden set cases (tests project)" "$(grep -c '"caseId"' tests/HealthQCopilot.Tests.Eval/GoldenSets/triage.json)"
c "workflows that run Tests.Eval" "$(grep -rl 'Tests.Eval' .github/workflows | wc -l)"
echo "--- H1"
c "PhiEncryptedString uses outside its own file" "$(grep -rn 'PhiEncryptedString' --include=*.cs src tests | grep -vc 'Security/PhiEncryptedString.cs')"
c "PhiRedaction feature-flag checks" "$(grep -rn 'IsEnabledAsync(HealthQFeatures.PhiRedaction' --include=*.cs src | wc -l)"
c "patient id written to localStorage (line)" "$(grep -n 'localStorage.setItem(RECENT_KEY' frontend/apps/shell/src/components/PatientQuickSearch.tsx | cut -d: -f1)"
echo "--- H2"
c "auth or limit calls in BFF" "$(grep -rnE 'AddAuthorization|AddAuthentication|UseAuthentication|AddHealthcareAuth|MaxExecutionDepth|AddMaxExecutionDepthRule|CostAnalyzer|Authorization"' --include=*.cs src/HealthQCopilot.BFF | wc -l)"
echo "--- H3"
c "route guard or role-check symbols in frontend apps" "$(grep -rnE 'ProtectedRoute|RequireAuth|RouteGuard|hasRole' --include=*.tsx --include=*.ts frontend/apps | grep -v node_modules | grep -vE '\.test\.|\.spec\.' | wc -l)"
echo "--- H4"
c "endpoints in DemoDataEndpoints.cs" "$(grep -cE "$E" src/HealthQCopilot.Agents/Endpoints/DemoDataEndpoints.cs)"
c "environment check before MapDemoDataEndpoints" "$(grep -B3 'MapDemoDataEndpoints' src/HealthQCopilot.Agents/Program.cs | grep -c 'IsDevelopment\|IsEnvironment')"
echo "--- H5"
c "migration files" "$(find src -path '*Migrations*' -name '*.cs' | wc -l)"
c "migration files with SQLite column types" "$(grep -rl 'Sqlite:Autoincrement\|"TEXT"\|"INTEGER"' --include=*.cs src | grep -c Migrations)"
c "PendingModelChangesWarning ignored (line)" "$(grep -n 'w.Ignore(RelationalEventId.PendingModelChangesWarning' src/HealthQCopilot.Infrastructure/Persistence/DatabaseExtensions.cs | cut -d: -f1)"
echo "--- H6"
c "continue-on-error: true" "$(grep -rnE 'continue-on-error:\s*true' .github/workflows | wc -l)"
c "|| true" "$(grep -rnE '\|\|\s*true' .github/workflows | wc -l)"
c "uses: lines / pinned to a full SHA" "$(grep -rnE '^\s*-?\s*uses:' .github/workflows | wc -l) / $(grep -rnE 'uses:\s*\S+@[0-9a-f]{40}' .github/workflows | wc -l)"
c ":latest references" "$(grep -rnE ':latest\b' .github/workflows infra src --include=*.yml --include=*.yaml --include=Dockerfile --include=*.bicep --include=*.sh | wc -l)"
echo "--- M1"
c "catch (Exception ...)" "$(grep -rnE 'catch\s*\(\s*Exception(\s+\w+)?\s*\)' --include=*.cs src | wc -l)"
c "bare catch" "$(grep -rnE 'catch\s*$|catch\s*\{' --include=*.cs src | wc -l)"
c "discarded tasks (_ = ...)" "$(grep -rnE '^\s*_ = (Task\.Run|\w+.*Async\()' --include=*.cs src | wc -l)"
c "GetAwaiter().GetResult() / .Wait()" "$(grep -rnE '\.GetAwaiter\(\)\.GetResult\(\)|\.Wait\(\)' --include=*.cs src | wc -l)"
echo "--- M2"
c "C# files over 800 lines (non-migration)" "$(git ls-files 'src/*.cs' | grep -v Migrations | xargs wc -l | awk '$1>800 && $2!="total"' | wc -l)"
c "TSX files over 600 lines (non-test)" "$(git ls-files 'frontend/apps/*.tsx' | grep -v '\.test\.' | xargs wc -l | awk '$1>600 && $2!="total"' | wc -l)"
echo "--- M3"
c "test.skip( calls" "$(grep -rnE '\btest\.skip\(' frontend --include=*.ts --include=*.tsx | grep -v node_modules | wc -l)"
c "of which conditional on a live response" "$(grep -rnE '\btest\.skip\(\s*!' frontend --include=*.ts --include=*.tsx | grep -v node_modules | wc -l)"
echo "--- M4"
c "tracked .map files" "$(git ls-files | grep -c '\.map$')"
c "tracked playwright report" "$(git ls-files frontend/playwright-report | wc -l)"
c "README licence line" "$(sed -n '/^## License/,$p' README.md | sed -n 3p)"
c "LICENSE first line" "$(head -1 LICENSE)"
echo "--- M5"
c "NuGetAuditSuppress entries" "$(grep -c 'NuGetAuditSuppress' Directory.Build.props)"
c "marked critical" "$(grep -ci 'critical' Directory.Build.props)"
